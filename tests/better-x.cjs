const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium', args:['--no-sandbox']});
  try {
    const page = await browser.newPage();
    page.setDefaultTimeout(5000);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('https://fixture.margonem.pl/**', route => route.fulfill({body:'<html><body></body></html>',contentType:'text/html'}));
    await page.goto('https://fixture.margonem.pl');
    const sources = Object.fromEntries(['catalogue.json','dock.js','modules/better-x.js'].map(file => [file, fs.readFileSync(path.join(__dirname,'../gogatki',file),'utf8')]));
    await page.evaluate(sources => {
      window.unsafeWindow = window;
      window.store = {'gogatek:modules:v1':{'better-x':true}};
      window.GM_getValue = (key, fallback) => store[key] ?? fallback;
      window.GM_setValue = (key, value) => {store[key] = value};
      window.GM_xmlhttpRequest = options => {const file = new URL(options.url).pathname.split('/gogatki/')[1];setTimeout(() => options.onload({status:200,responseText:sources[file]}),0)};
      window.requests = [];
      window._g = q => requests.push(q);
      const d = {id:2,nick:'Enemy',lvl:100,relation:3,x:2,y:1};
      window.players = {2:{d,addShowEqAndMessageToMenu(menu){menu.push(['Original',()=>{}])}}};
      window.Engine = {hero:{d:{id:1,x:0,y:0},autoPath:{road:[]},searchPath(){this.autoPath.road=[1,2]},clearAutoPathOfHero(){this.autoPath.road=[]}},others:{check:()=>players,getById:id=>players[id],getDrawableList:()=>[]},lock:{add(){},remove(){},check:()=>false},stepsToSend:{reset(){}},map:{d:{id:1}}};
    }, sources);
    await page.addScriptTag({path:path.join(__dirname,'../gogatki/gogatki.user.js')});
    await page.waitForFunction(() => window.WildHuntStandalone && window.__gogatkiTileDock);
    const main = page.locator('#gogatek-panel');
    await main.locator('.launcher').evaluate(el => el.click());
    assert.equal(await main.getByRole('checkbox',{name:'Better X',exact:true}).isChecked(),true);
    await main.locator('.launcher').evaluate(el => el.click());
    const addon = page.locator('#wild-hunt-standalone');
    assert.equal(await addon.locator('strong').textContent(),'Better X');
    await page.keyboard.press('x');
    assert.equal(await page.evaluate(()=>WildHuntStandalone.target),'2');
    await page.waitForTimeout(400);
    assert.ok(await page.evaluate(()=>requests.length>=2));
    await addon.locator('#gear').click({button:'right'});
    await page.waitForFunction(()=>document.getElementById('wild-hunt-standalone').hasAttribute('data-gogatki-docked'));
    const tile = page.locator('#gogatki-tile-dock > button[data-gogatki-dock-item="wild-hunt-standalone"]');
    assert.equal(await tile.locator('svg circle').count(),2);
    await tile.click();
    await page.waitForFunction(()=>!document.getElementById('wild-hunt-standalone').hasAttribute('data-gogatki-docked'));
    await addon.locator('#gear').click();
    const shortcut = addon.locator('#settings input[type=text]').first();
    await shortcut.fill('z');
    assert.equal(await page.evaluate(()=>store['better-x:global:v1'].nearestKey),'z');
    await shortcut.blur();
    await page.keyboard.press('j');
    assert.equal(await page.evaluate(()=>WildHuntStandalone.target),null);
    await shortcut.blur();
    await page.keyboard.press('z');
    assert.equal(await page.evaluate(()=>WildHuntStandalone.target),'2');
    await page.evaluate(()=>document.dispatchEvent(new KeyboardEvent('keydown',{key:'j',bubbles:true})));
    await shortcut.focus();
    await page.keyboard.press('z');
    assert.equal(await page.evaluate(()=>WildHuntStandalone.target),null);
    assert.deepEqual(errors,[]);
    console.log('PASS: catalogue loading, enabled module, X attack, repeated attack, dock crosshair, collapse/restore, custom shortcut, GM storage, typing guard');
  } finally { await browser.close(); }
})().catch(error => {console.error(error);process.exitCode=1});
